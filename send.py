"""Step 7 - Send via Gmail. The TO address is hard-coded to your own inbox (case rule,
and L4's 9-check boundary: no email reaches a real prospect without human review).

The prospect's name and real address go in a review footer, so the email in your inbox
reads exactly as the prospect would see it, plus what you need to approve it.

L6 retry table: SMTP timeout = transient, nothing downstream depends on it -> retry, then skip.
Auth failure = permanent -> abort the send step for the whole run (it will fail for everyone).
"""
import smtplib
import ssl
import time
from email.message import EmailMessage
from typing import Dict

import config


class SendAuthError(Exception):
    pass


def _send_resend(subject: str, text: str) -> str:
    """Resend HTTP API. Same retry rules as SMTP: auth errors are permanent, the rest transient."""
    import requests

    for attempt in (1, 2, 3):
        try:
            r = requests.post(
                "https://api.resend.com/emails",
                headers={"Authorization": f"Bearer {config.RESEND_API_KEY}"},
                json={"from": config.RESEND_FROM, "to": [config.SEND_TO], "subject": subject, "text": text},
                timeout=30,
            )
        except requests.RequestException as e:
            if attempt == 3:
                return f"skipped after 3 attempts: {type(e).__name__}"
            time.sleep(2 * attempt)
            continue
        if r.status_code in (401, 403):
            raise SendAuthError(f"Resend rejected the request ({r.status_code}): {r.text[:160]}")
        if r.ok:
            return "sent"
        if r.status_code < 500 and r.status_code != 429:
            return f"not sent: Resend {r.status_code}: {r.text[:160]}"
        if attempt == 3:
            return f"skipped after 3 attempts: Resend {r.status_code}"
        time.sleep(2 * attempt)
    return "skipped"


def send(email: Dict, poc: Dict, company: str, reason: str) -> str:
    if not config.SEND_TO:
        raise SendAuthError("SEND_TO is not set (the one inbox every draft goes to)")
    if not config.RESEND_API_KEY and not (config.GMAIL_ADDRESS and config.GMAIL_APP_PASSWORD):
        raise SendAuthError("No sender configured: set RESEND_API_KEY, or GMAIL_ADDRESS + GMAIL_APP_PASSWORD")

    msg = EmailMessage()
    msg["From"] = f"{config.SENDER_NAME} <{config.GMAIL_ADDRESS}>"
    msg["To"] = config.SEND_TO                            # hard-coded: your own inbox
    msg["Subject"] = email["subject"]
    footer = (
        "\n\n-----\n[REVIEW BEFORE SENDING - generated by the Sprinto outreach pipeline]\n"
        f"Intended recipient: {poc['first_name']} {poc['last_name']}, {poc['position']} at {company}"
        f" <{poc['email']}>\n"
        f"Why this company: {reason}\n"
        f"Why this person: {poc['why']}\n"
        f"Hook used: {email['hook_fact_used']}\n"
        f"Why this angle: {email['why_this_angle']}"
        + (f"\nAuto-check warnings: {email['check_problems']}" if email.get("check_problems") else "")
    )
    msg.set_content(email["body"] + footer)

    if config.RESEND_API_KEY:
        return _send_resend(email["subject"], email["body"] + footer)

    for attempt in (1, 2, 3):
        try:
            with smtplib.SMTP_SSL("smtp.gmail.com", 465, context=ssl.create_default_context(), timeout=30) as s:
                s.login(config.GMAIL_ADDRESS, config.GMAIL_APP_PASSWORD)
                s.send_message(msg)
            return "sent"
        except smtplib.SMTPAuthenticationError as e:
            raise SendAuthError(f"Gmail rejected the login: {e.smtp_error[:100]!r}")
        except (smtplib.SMTPException, OSError) as e:
            if attempt == 3:
                return f"skipped after 3 attempts: {type(e).__name__}"
            time.sleep(2 * attempt)
    return "skipped"
